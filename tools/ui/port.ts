// Carries the design system into the game: design/system.css becomes src/ui/system/system.css, the fonts go to
// public/fonts and the paper grain beside the stylesheet. The design folder stays the one source; this only changes
// what a game served from its own folder needs (where the files are, swap instead of block, flat sample colours in
// place of the frames' backdrop photographs). tests/ui-system.test.ts fails when the two drift apart.
// Usage: node tools/ui/port.ts [--check]
import { copyFileSync, existsSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const ROOT = join(import.meta.dirname, '..', '..')
export const FONTS = ['caslon-text.woff2', 'caslon-text-italic.woff2', 'league-gothic.woff2', 'big-shoulders-stencil.woff2']
export const LICENCES = ['OFL-LibreCaslon.txt', 'OFL-LeagueGothic.txt', 'OFL-BigShouldersStencil.txt']
// The frames are drawn over photographs of the scene; the game's kit page uses the scene's own sample colours.
const BACKDROPS: Record<string, string> = {
  'play-july.jpg': '#4f7a34', 'play-snow.jpg': '#e2e5e8', 'winter-night.jpg': '#3a4a6a', 'title.jpg': '#c98f5a', 'play-october.jpg': '#7a6a4a',
}

// The materials every screen shares, old or rebuilt: the tokens, the type, the paper, the buttons and the weight
// every control carries (data-w), the stamps.
// Every other rule of the system is a component and reaches only inside an element marked .sys, so the old screens'
// markup (which uses some of the same class names) is not restyled under them while they wait to be rebuilt.
const GLOBAL = /^(:root|\*|html|body|button|p\b|h[1-4]\b|ul\b|ol\b|b\b|fieldset|:focus-visible|\[data-w|:is\(\[data-w|:is\(\.seg-in|\.seg-in|\.(sr|i|veil|stage|t-[a-z]+|num|tab|it|quiet|c-[a-z]+|rule|lead|btn|key|iconbtn|sheet|mount|s-[a-z]+|stamp)(?![a-z0-9-]))/
const SCOPE = ':is(.sys, .sys *)'

function scopeSelector(sel: string): string {
  const s = sel.trim()
  if (!s || GLOBAL.test(s)) return sel
  let depth = 0, last = 0
  for (let i = 0; i < s.length; i++) {
    const c = s[i]
    if (c === '(' || c === '[') depth++
    else if (c === ')' || c === ']') depth--
    else if (depth === 0 && (c === ' ' || c === '>' || c === '+' || c === '~')) last = i + 1
  }
  const head = s.slice(0, last), subject = s.slice(last)
  const pe = subject.search(/::[a-z-]+$/)
  const lead = sel.slice(0, sel.length - sel.trimStart().length)
  return lead + head + (pe >= 0 ? subject.slice(0, pe) + SCOPE + subject.slice(pe) : subject + SCOPE)
}

function splitTop(s: string): string[] {
  const out: string[] = []
  let depth = 0, cur = ''
  for (const c of s) {
    if (c === '(' || c === '[') depth++
    else if (c === ')' || c === ']') depth--
    if (c === ',' && depth === 0) { out.push(cur); cur = '' } else cur += c
  }
  out.push(cur)
  return out
}

// Scopes every rule's selectors, skipping @font-face and @keyframes and keeping comments where they are.
function scope(css: string): string {
  let out = '', buf = '', i = 0
  const stack: string[] = []
  while (i < css.length) {
    if (css.startsWith('/*', i)) { const j = css.indexOf('*/', i) + 2; buf += css.slice(i, j); i = j; continue }
    const c = css[i]
    if (c === '{') {
      const p = buf.replace(/\/\*[\s\S]*?\*\//g, '').trim()
      const skip = stack.includes('skip')
      const kind = p.startsWith('@') ? (/^@(font-face|keyframes)/.test(p) ? 'skip' : 'at') : 'rule'
      if (kind === 'rule' && !skip) {
        const m = buf.match(/^((?:\s|\/\*[\s\S]*?\*\/)*)([\s\S]*)$/)!
        buf = m[1] + splitTop(m[2]).map(scopeSelector).join(',')
      }
      out += buf + '{'
      buf = ''
      stack.push(skip ? 'skip' : kind)
      i++
      continue
    }
    if (c === '}') { out += buf + '}'; buf = ''; stack.pop(); i++; continue }
    if (c === ';' && stack[stack.length - 1] !== 'rule') { out += buf + ';'; buf = ''; i++; continue }
    buf += c
    i++
  }
  return out + buf
}

export function port(css: string): string {
  let out = css
    .replace(/url\(fonts\/([a-z-]+\.woff2)\)/g, 'url(/fonts/$1)')
    .replace(/font-display: block/g, 'font-display: swap')
    .replace(/url\(img\/grain\.png\)/g, 'url(./grain.png)')
    .replace(/url\(backdrops\/([a-z-]+\.jpg)\)/g, (_, f: string) => `linear-gradient(${BACKDROPS[f]}, ${BACKDROPS[f]})`)
  out = `/* Generated by tools/ui/port.ts from design/system.css: change that file, then run the tool. */\n${scope(out)}`
  return out
}

if (process.argv[1]?.endsWith('port.ts')) {
  const css = port(readFileSync(join(ROOT, 'design', 'system.css'), 'utf8'))
  const target = join(ROOT, 'src', 'ui', 'system', 'system.css')
  if (process.argv.includes('--check')) {
    const now = existsSync(target) ? readFileSync(target, 'utf8') : ''
    if (now !== css) { console.error('src/ui/system/system.css is out of date: run node tools/ui/port.ts'); process.exit(1) }
    process.exit(0)
  }
  writeFileSync(target, css)
  for (const f of FONTS) copyFileSync(join(ROOT, 'design', 'fonts', f), join(ROOT, 'public', 'fonts', f))
  for (const f of LICENCES) copyFileSync(join(ROOT, 'design', 'fonts', f), join(ROOT, 'public', 'fonts', f))
  copyFileSync(join(ROOT, 'design', 'img', 'grain.png'), join(ROOT, 'src', 'ui', 'system', 'grain.png'))
  console.log('ported design/system.css, fonts and grain')
}
